// cwd가 project root의 하위 디렉터리인 세션(project root 상대경로가 모델 cwd에서는
// 안 열리는 경우). 함수 단위로 검증하는 이유: hook 전체 경로로 재현하려면 프로젝트를
// HOME 하위에 만들어야 한다(config 부모 탐색이 HOME 경계까지만 올라간다) — tmpdir은
// HOME 밖이라 하위 cwd에서 설정 자체를 못 찾고 이 분기까지 도달하지 않는다.
test('display_card_path: cwd 하위면 상대경로, 그 밖이면 절대경로 (../ 사슬 회피)', () => {
  const out = execFileSync('python3', ['-c', [
    'import json, sys, pathlib',
    'sys.path.insert(0, "core")',
    'import recall',
    // 프로덕션에서 path는 resolve_wiki_result_path가 이미 resolve()한 값이다(동일 조건).
    'card = pathlib.Path("/tmp/p/.auto-context/wiki/decisions/x.md").resolve()',
    'print(json.dumps({',
    '  "at_root": recall.display_card_path(card, "/tmp/p"),',
    '  "at_subdir": recall.display_card_path(card, "/tmp/p/docs"),',
    '}))',
  ].join('\n')], { encoding: 'utf8' });
  const r = JSON.parse(out);
  assert.equal(r.at_root, '.auto-context/wiki/decisions/x.md', 'cwd == project root → 상대경로');
  assert.ok(isAbsolute(r.at_subdir), `하위 cwd에서는 절대경로: ${r.at_subdir}`);
  assert.doesNotMatch(r.at_subdir, /\.\./, '../ 사슬을 만들지 않는다');
});

