test('주입에 카드 본문이 포함되고 frontmatter title이 쓰인다 (섹션 헤딩 Summary가 title로 새지 않음)', () => {
  withProject({
    cards: { 'card.md': card(VERIFIED_FM, '설정은 .auto-context/settings.json 한 곳에서만 읽는다.') },
  }, ({ dir, fixture, write }) => {
    // 데몬이 주는 title은 frontmatter title이 아니라 첫 섹션 헤딩이다 — 라이브 재현.
    write([{ file: 'proj-wiki/decisions/card.md', title: 'Summary', score: 1 }]);
    const ctx = contextOf({ prompt: PROMPT, cwd: dir }, { QMD_QUERY_FIXTURE: fixture });
    assert.ok(ctx);
    assert.match(ctx, /설정은 \.auto-context\/settings\.json 한 곳에서만 읽는다\./, '카드 본문이 주입돼야 함');
    assert.match(ctx, / - 카드 정식 제목 — 설정 레이아웃 결정/, 'frontmatter title 사용');
    assert.doesNotMatch(ctx, /- Summary/, '데몬이 준 섹션 헤딩이 title로 새면 안 됨');
    assert.doesNotMatch(ctx, /## Summary/, 'Summary 헤딩 자체는 주입하지 않음(중복 라벨)');
    assert.doesNotMatch(ctx, /Auto-generated by qmd-auto-context/, '상투구는 주입하지 않음');
    assert.match(ctx, /부족할 때만 위 경로를 Read\./, '요약/원문 구분 안내(축약본)');
  });
});

