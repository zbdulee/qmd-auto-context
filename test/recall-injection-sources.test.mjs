test('injectSourcePathsPerCard 로 상한을 조절하고 0 이면 원문 경로 주입을 끈다', () => {
  const cards = { 'card.md': card('카드', '본문.', [fileEntry('docs/a.md'), fileEntry('docs/b.md')]) };
  const raw = { 'docs/a.md': 'a\n', 'docs/b.md': 'b\n' };
  const results = [{ file: 'proj-wiki/decisions/card.md', title: 'Summary', score: 1 }];
  withProject({ settings: { injectSourcePathsPerCard: 1 }, cards, raw }, ({ write, run }) => {
    write(results);
    assert.deepEqual(sourceLines(run()), ['docs/a.md']);
  });
  withProject({ settings: { injectSourcePathsPerCard: 0 }, cards, raw }, ({ log, write, run }) => {
    write(results);
    const ctx = run();
    assert.deepEqual(sourceLines(ctx), []);
    assert.doesNotMatch(ctx, /↳/);
    const sel = selection(log);
    assert.equal(sel.inject_source_paths_per_card, 0);
    // QMD_RECALL_LOG가 켜져 있으면 상한 0에서도 **분류만** 돌린다 — 그래야 3단계의
    // cards_all_sources_missing이 이 설정에 의해 죽지 않는다(카드는 여전히 캐논으로
    // 주입된다). 주입은 여전히 0이고 출력은 바이트 동일하다(위 두 단정).
    assert.equal(sel.source_entries, 2, '진단 로그가 켜진 동안은 항목을 분류한다(주입은 0)');
    assert.equal(sel.sources_injected, 0);
    assert.equal(sel.cards_all_sources_missing, 0, '두 원문이 다 살아 있으므로 0');
  });
});

