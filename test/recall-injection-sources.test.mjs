      run();
      // 주입 목록(`_wiki_sources`)으로 판정하면 partial/dup 까지 세어 3이 된다 —
      // 살아 있는 파일 소스 수를 따로 세야 한다(관측 전용 모드에서는 목록이 항상 빈다).
