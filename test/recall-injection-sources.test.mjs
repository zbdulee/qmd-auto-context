test('cwd 가 프로젝트 하위 디렉터리여도 원문 경로가 열린다 (base 는 cwd 가 아니라 project root)', () => {
  // sources[].path 는 project root 상대 POSIX 다(wiki_compile_enqueue._source_record).
  // cwd 를 base 로 쓰면 하위 디렉터리 세션에서 정상 소스가 미존재/traversal 로 오판된다.
  // HOME 하위에 만들어야 config 부모 탐색(HOME 경계)이 하위 cwd 에서도 동작한다.
  const base = mkdtempSync(join(homedir(), '.qmd-src-e2e-'));
  const dir = join(base, '한글 프로젝트');
  mkdirSync(dir, { recursive: true });
  project(dir, {
    cards: { 'card.md': card('카드', '본문.', [fileEntry('docs/원문 문서.md')]) },
    raw: { 'docs/원문 문서.md': 'a\n' },
  });
  const sub = join(dir, 'docs', '깊은 폴더');
  mkdirSync(sub, { recursive: true });
  const fixture = join(dir, 'fixture.json');
  writeFileSync(fixture, JSON.stringify({ results: [{ file: 'proj-wiki/decisions/card.md', title: 'Summary', score: 1 }] }));
  try {
    for (const cwd of [dir, sub]) {
      const ctx = contextOf({ prompt: PROMPT, cwd }, { QMD_QUERY_FIXTURE: fixture });
      const [line] = sourceLines(ctx);
      assert.ok(line, `cwd=${cwd} 에서 원문 경로가 주입돼야 함`);
      const resolved = isAbsolute(line) ? line : join(cwd, line);
      assert.ok(existsSync(resolved), `cwd=${cwd} 원문 경로가 실제 파일이어야 함: ${line}`);
      // cwd 하위면 상대, 밖이면 절대 — 1단계 카드 경로와 같은 규칙.
      assert.equal(isAbsolute(line), cwd !== dir, `표시 규칙 불일치: ${line}`);
    }
  } finally {
    removeTemp(base);
  }
});

