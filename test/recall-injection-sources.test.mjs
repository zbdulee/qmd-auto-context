test('flow mapping 왕복: 특수문자·개행·유니코드·구분자를 담아도 emit→parse 가 원값을 돌려준다', () => {
  const r = py([
    'import yaml_scalars as ys',
    'cases = [',
    '  {"kind": "file", "path": "docs/a.md"},',
    '  {"kind": "file", "path": "쉼표, 그리고 \\"인용\\" 과 백슬래시 \\\\ 경로.md"},',
    '  {"kind": "file", "path": "line\\nbreak.md", "collection": "c"},',
    '  {"kind": "url", "path": "https://x/y?a=1,b=2"},',
    '  {"path": "}중괄호{.md"},',
    '  {"path": "탭\\there.md"},',
    ']',
    'out = []',
    'for case in cases:',
    '    text = ys.dump_flow_mapping(case)',
    '    back, issue = ys.load_flow_mapping(text)',
    '    out.append({"text": text, "ok": back == case, "issue": issue})',
    'print(json.dumps(out, ensure_ascii=False))',
  ]);
  for (const row of r) {
    assert.equal(row.ok, true, `왕복 실패: ${row.text}`);
    assert.equal(row.issue, '', `왕복에 문제 신호가 붙으면 안 됨: ${row.text}`);
    assert.equal(row.text.split('\n').length, 1, `표기가 여러 줄이면 frontmatter 를 벗어난다: ${row.text}`);
  }
});

test('emit 표기는 표준 YAML 이다 (PyYAML 대조 — 런타임 의존이 아니라 테스트에서만)', () => {
  const r = py([
    'import yaml_scalars as ys',
    'try:',
    '    import yaml',
    'except ImportError:',
    '    print(json.dumps({"skipped": True})); raise SystemExit(0)',
    'cases = [',
    '  {"kind": "file", "path": "docs/a.md"},',
    '  {"kind": "file", "path": "쉼표, \\"인용\\", 백슬래시 \\\\ 와 개행\\n."},',
    '  {"path": "}b{"}, {"path": "  공백  유지  "},',
    ']',
    'out = []',
    'for case in cases:',
    '    text = ys.dump_flow_mapping(case)',
    '    out.append({"text": text, "same": yaml.safe_load(text) == case})',
    'print(json.dumps({"skipped": False, "rows": out}, ensure_ascii=False))',
  ]);
  if (r.skipped) return;
  for (const row of r.rows) assert.equal(row.same, true, `PyYAML 이 다르게 읽음: ${row.text}`);
});

test('wiki_compile 이 쓴 sources 를 recall 이 그대로 읽는다 (쓰기/읽기 SSOT 왕복)', () => {
  // 규칙이 두 벌로 갈리는 순간 조용히 깨지는 클래스다. 실제 writer 함수의 산출물을
  // 실제 reader 함수로 되읽어 고정한다.
  const r = py([
    'import recall, wiki_compile, yaml_scalars',
    'page = wiki_compile.markdown_page(',
    '  {"title": "왕복", "suggestedType": "concept",',
    '   "sources": [{"kind": "file", "path": "docs/쉼표, \\"인용\\".md"}, {"nope!": "x"}]},',
    '  "본문.", "verified", [], "deadbeef")',
    'block = page[3:page.index("\\n---", 3)]',
    'entries = recall.frontmatter_source_entries(block)',
    'parsed = [yaml_scalars.load_flow_mapping(e) for e in entries]',
    'print(json.dumps({"entries": entries, "paths": [p.get("path", "") for p, _ in parsed],',
    '                  "issues": [i for _, i in parsed]}, ensure_ascii=False))',
  ]);
  // path 없는 항목(`{"nope!": "x"}`)은 원문 추적에 쓸 수 없어 writer 가 버린다.
  assert.equal(r.entries.length, 1, 'writer 가 쓴 항목 수를 reader 가 그대로 본다');
  assert.equal(r.paths[0], 'docs/쉼표, "인용".md', '값이 역이스케이프돼 원래 경로가 복원된다');
  assert.deepEqual(r.issues, [''], 'writer 산출물에는 파싱 문제가 없어야 한다');
});

