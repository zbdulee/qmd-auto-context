// 2단계: wiki 카드의 원문 경로(`sources[].path`) 주입.
//
// 배경: 1단계로 카드 본문·title·Read 가능한 카드 경로가 주입되게 됐지만, 카드에서 원문으로
// 가는 링크가 없어 카드가 막다른 길이었다(wikiOnly 아키텍처의 전제가 "카드에 원문 링크가
// 있으니 raw 검색이 불필요"다). 이 파일이 고정하는 것 세 묶음:
//   (1) emit/parse 쌍이 갈리지 않는다 — flow mapping 규칙은 yaml_scalars가 SSOT다.
//       이 저장소는 규칙이 갈려 두 번 조용히 깨졌다(title 8/731장 오염, qmd:auto 마커).
//   (2) `sources[].path`는 **모델 제공 값**이다 — traversal·미존재·개행을 주입하지 않는다.
//   (3) 개수 상한·중복 제거·진단 카운터. 무흔적 실패 금지.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir, homedir } from 'node:os';
import { join, isAbsolute, dirname } from 'node:path';
import { removeTemp } from './helpers/temp.mjs';

const PROMPT = 'config layout decision 내용을 알려줘';
const SOURCE_PREFIX = '  ↳ ';

function runRecall(payload, env = {}) {
  return execFileSync('python3', ['core/recall.py'], {
    input: JSON.stringify(payload),
    encoding: 'utf8',
    env: { ...process.env, ...env },
  });
}

function contextOf(payload, env = {}) {
  const out = runRecall(payload, env).trim();
  if (!out) return null;
  return JSON.parse(out).hookSpecificOutput.additionalContext;
}

function sourceLines(ctx) {
  return ctx.split('\n').filter((l) => l.startsWith(SOURCE_PREFIX)).map((l) => l.slice(SOURCE_PREFIX.length));
}

// 가장 **마지막** selection 줄을 본다(한 로그에 여러 번 실행하는 테스트가 있다).
function selection(logPath) {
  const lines = readFileSync(logPath, 'utf8').trim().split('\n').map(JSON.parse)
    .filter((l) => l.event === 'qmd_recall_selection');
  return lines[lines.length - 1];
}

// 카드 1장. sources 는 실제 compile 산출물과 같은 flow mapping 표기를 쓴다.
function card(title, summary, sourceEntries = [], status = 'verified') {
  const fm = [
    `title: "${title}"`,
    `status: ${status}`,
    'createdBy: qmd-auto-context',
    'reviewed: false',
    'sources:',
    ...(sourceEntries.length ? sourceEntries.map((e) => `  - ${e}`) : ['  - {kind: unknown}']),
    'triggers:',
    '  - "post_tool_source"',
  ].join('\n');
  return [
    '---', fm, '---', '',
    '> Auto-generated by qmd-auto-context from conversation/work context. Review, edit, or delete if wrong.',
    '',
    '<!-- qmd:auto:start id="main" sourceHash="deadbeef" -->',
    '## Summary',
    summary,
    '<!-- qmd:auto:end -->',
    '',
  ].join('\n');
}

function fileEntry(path) {
  return `{kind: "file", path: "${path}"}`;
}

function project(dir, { settings = {}, cards = {}, raw = {} } = {}) {
  mkdirSync(join(dir, '.auto-context', 'wiki', 'decisions'), { recursive: true });
  mkdirSync(join(dir, 'docs'), { recursive: true });
  writeFileSync(join(dir, '.auto-context', 'settings.json'), JSON.stringify({
    indexing: true,
    collections: ['proj-wiki', 'proj-docs'],
    collectionPaths: { 'proj-wiki': '.auto-context/wiki', 'proj-docs': 'docs' },
    collectionRoles: { 'proj-wiki': 'wiki', 'proj-docs': 'raw' },
    recallStrategy: 'wikiOnly',
    topN: 3,
    ...settings,
  }));
  for (const [name, body] of Object.entries(cards)) {
    writeFileSync(join(dir, '.auto-context', 'wiki', 'decisions', name), body);
  }
  for (const [rel, body] of Object.entries(raw)) {
    const target = join(dir, rel);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, body);
  }
}

function withProject(opts, fn) {
  const dir = mkdtempSync(join(tmpdir(), 'qmd-src-'));
  project(dir, opts);
  const fixture = join(dir, 'fixture.json');
  const log = join(dir, 'recall.jsonl');
  const write = (results) => writeFileSync(fixture, JSON.stringify({ results }));
  const run = (payload = {}) => contextOf(
    { prompt: PROMPT, cwd: dir, ...payload },
    { QMD_QUERY_FIXTURE: fixture, QMD_RECALL_LOG: log },
  );
  try {
    return fn({ dir, fixture, log, write, run });
  } finally {
    removeTemp(dir);
  }
}

// python 헬퍼. `arg` 를 주면 argv[1] 로 넘어간다(JS 문자열을 python 리터럴로 끼워 넣다가
// 인용부호가 겹치는 것을 피한다 — 이 파일은 sources 표기 자체를 다루므로 인용부호가 많다).
function py(code, arg) {
  const args = ['-c', ['import json, sys', 'sys.path.insert(0, "core")', ...code].join('\n')];
  if (arg !== undefined) args.push(arg);
  return JSON.parse(execFileSync('python3', args, { encoding: 'utf8' }));
}

