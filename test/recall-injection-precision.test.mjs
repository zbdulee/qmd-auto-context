const FILLER = '앞부분 문단이며 이 카드의 도입부에 해당하는 내용을 충분히 길게 채운다. '.repeat(20);

test('긴 카드에서 매칭 줄이 auto 블록 안이면 그 지점부터 인용한다', () => {
  const built = card(VERIFIED_FM, {
    head: FILLER,
    match: '핵심결론토큰: 격리 수준은 read committed 로 고정한다.',
    tail: '뒤에 이어지는 별개 문단이다.',
  });
  withProject({ cards: { 'card.md': built.text } }, ({ dir, fixture, write }) => {
    write([{ file: 'proj-wiki/decisions/card.md', title: 'Summary', score: 1, line: built.marks.match }]);
    const ctx = contextOf({ prompt: PROMPT, cwd: dir }, { QMD_QUERY_FIXTURE: fixture });
    report('B/mid-body', ctx);
    const body = bodyLines(ctx).join('\n');
    assert.match(body, /핵심결론토큰/, '매칭 문단이 인용에 들어와야 한다');
    assert.match(body, /앞부분 생략/, '앞을 건너뛴 사실을 표시한다');
    assert.ok(body.length <= 600, `상한은 그대로 600: ${body.length}자`);
  });
});

test('매칭 줄이 frontmatter면 기존대로 본문 앞부분을 인용한다', () => {
  const built = card(VERIFIED_FM, {
    head: FILLER,
    match: '핵심결론토큰: 이 문단은 선택되지 않아야 한다.',
  });
  withProject({ cards: { 'card.md': built.text } }, ({ dir, fixture, write }) => {
    // line 2 = frontmatter의 title 줄. 실측 "n8n 멀티팀" 케이스(line 2, 무용).
    write([{ file: 'proj-wiki/decisions/card.md', title: 'Summary', score: 1, line: 2 }]);
    const ctx = contextOf({ prompt: PROMPT, cwd: dir }, { QMD_QUERY_FIXTURE: fixture });
    report('B/frontmatter', ctx);
    const body = bodyLines(ctx).join('\n');
    assert.match(body, /^앞부분 문단이며/, '본문 앞부분부터 인용(기존 동작)');
    assert.doesNotMatch(body, /앞부분 생략/, '생략 표시가 붙으면 안 된다');
  });
});

test('짧은 카드는 매칭 위치와 무관하게 전문을 인용한다 (상한 미만이면 잃을 것이 없다)', () => {
  const built = card(VERIFIED_FM, {
    head: '첫 문단이다.',
    match: '둘째 문단에 매칭이 있다.',
  });
  withProject({ cards: { 'card.md': built.text } }, ({ dir, fixture, write }) => {
    write([{ file: 'proj-wiki/decisions/card.md', title: 'Summary', score: 1, line: built.marks.match }]);
    const ctx = contextOf({ prompt: PROMPT, cwd: dir }, { QMD_QUERY_FIXTURE: fixture });
    const body = bodyLines(ctx).join('\n');
    assert.match(body, /첫 문단이다/, '상한 안이면 앞부분도 그대로 남는다');
    assert.match(body, /둘째 문단에 매칭이 있다/);
    assert.doesNotMatch(body, /앞부분 생략/);
  });
});

